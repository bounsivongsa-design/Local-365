export function getCategoryById(id: string): BusinessCategory | undefined {
  return BUSINESS_CATEGORIES.find((cat) => cat.id === id);
}

export function getSubcategoryById(categoryId: string, subcategoryId: string): Subcategory | undefined {
  const category = getCategoryById(categoryId);
  return category?.subcategories.find((sub) => sub.id === subcategoryId);
}

export function searchCategories(query: string): BusinessCategory[] {
  const lowerQuery = query.toLowerCase();
  return BUSINESS_CATEGORIES.filter(
    (cat) =>
      cat.name.toLowerCase().includes(lowerQuery) ||
      cat.description.toLowerCase().includes(lowerQuery) ||
      cat.subcategories.some(
        (sub) =>
          sub.name.toLowerCase().includes(lowerQuery) ||
          sub.description.toLowerCase().includes(lowerQuery)
      )
  );
}

export function getAllSubcategories(): Subcategory[] {
  return BUSINESS_CATEGORIES.flatMap((cat) => cat.subcategories);
}

export function getCategoryCount(): number {
  return BUSINESS_CATEGORIES.length;
}

export function getSubcategoryCount(): number {
  return BUSINESS_CATEGORIES.reduce((sum, cat) => sum + cat.subcategories.length, 0);
}

export const EMERGENCY_CATEGORIES = ["hvac", "electrical", "plumbing", "roofing", "locksmith", "towing", "storm-damage"] as const;

export function isEmergencyCategory(subcategoryId: string): boolean {
  return (EMERGENCY_CATEGORIES as readonly string[]).includes(subcategoryId);
}
